import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const {chromium}=createRequire(import.meta.url)(process.argv[2]);
const meta=JSON.parse(fs.readFileSync(process.argv[4],'utf8'));assert.equal(meta.synthetic,true);
const out=path.resolve('../evidence/focus-drag');fs.mkdirSync(out,{recursive:true});
const browser=await chromium.launch({executablePath:process.argv[3],headless:true});
const checks=[],errors=[];
try{
 for(const width of [1440,390]){
  const context=await browser.newContext({viewport:{width,height:900}}),p=await context.newPage();
  p.on('pageerror',e=>errors.push(e.message));p.setDefaultTimeout(10000);
  const state=()=>p.evaluate(()=>JSON.parse(localStorage.getItem(Object.keys(localStorage).find(k=>k.startsWith('zhixu-focus-v1')))));
  await p.goto(meta.candidate+'/#today');await p.locator('[data-action="focus-start"]').click();await p.locator('#focus-start-form [type="submit"]').click();
  await p.locator('#focus-home .focus-clock').waitFor();await p.locator('#focus-start-form').waitFor({state:'hidden'});await p.goto(meta.candidate+'/#library');await p.locator('.focus-mini').waitFor();await p.waitForTimeout(450);
  await p.locator('.focus-square').click();
  const expansion=await p.locator('.focus-clock').evaluate(async n=>{const values=[];for(let i=0;i<30;i++){await new Promise(requestAnimationFrame);const r=n.getBoundingClientRect();values.push({x:r.x,right:r.right,width:n.offsetWidth});}return values;});
  assert.ok(expansion.every(r=>r.right<=width-7&&r.x>=7),'expanded animation must stay inside viewport');
  assert.ok(expansion.every(r=>r.width===(width===390?260:280)),`panel layout width must stay constant during animation: ${JSON.stringify(expansion)}`);
  await p.screenshot({path:path.join(out,`expanded-${width}.png`)});
  const dock=await p.locator('#focus-top-dock').boundingBox(),handle=await p.locator('.focus-drag').boundingBox();
  await p.mouse.move(handle.x+handle.width/2,handle.y+handle.height/2);await p.mouse.down();
  await p.mouse.move(dock.x+18,dock.y+18,{steps:15});
  await p.locator('.focus-dock-preview.focus-mini').waitFor();
  assert.equal(await p.locator('.focus-clock').evaluate(n=>n.getAnimations().length)>0,true);
  await p.waitForTimeout(320);
  assert.equal(await p.locator('.focus-mini').evaluate(n=>getComputedStyle(n).boxShadow),'none','dock preview must not show an orange selection halo');
  let before=await p.locator('.focus-clock').boundingBox();
  await p.mouse.move(dock.x+28,dock.y+25,{steps:3});await p.waitForTimeout(1100);
  let after=await p.locator('.focus-clock').boundingBox();
  assert.ok(after.x>before.x+5,'unreleased preview must follow pointer, not pin itself to dock');
  assert.equal((await state()).position,null);
  await p.screenshot({path:path.join(out,`held-mini-${width}.png`)});
  await p.mouse.move(width-70,300,{steps:15});await p.waitForTimeout(320);
  assert.equal(await p.locator('.focus-mini').count(),0,'dragging away in same gesture must restore panel');
  assert.equal((await state()).position,null,'gesture must not persist before mouse release');
  await p.screenshot({path:path.join(out,`held-expanded-${width}.png`)});
  await p.mouse.move(dock.x+18,dock.y+18,{steps:15});await p.waitForTimeout(300);await p.mouse.up();await p.waitForTimeout(150);
  assert.equal(await p.locator('.focus-mini').count(),1);assert.equal((await state()).position,null);
  assert.equal(await p.locator('.focus-mini').evaluate(n=>getComputedStyle(n).boxShadow),'none','docked square must not retain a selection halo');
  let r=await p.locator('.focus-square').boundingBox();await p.mouse.move(r.x+16,r.y+16);await p.mouse.down();await p.mouse.move(width-85,350,{steps:15});await p.waitForTimeout(320);
  assert.equal(await p.locator('.focus-mini').count(),1,'a new drag of a docked square must remain a square');
  await p.mouse.up();await p.waitForTimeout(150);assert.ok((await state()).position);
  await p.reload();await p.locator('.focus-mini').waitFor();r=await p.locator('.focus-mini').boundingBox();assert.ok(r.y>300);
  checks.push(`${width}px: full-width expansion stays in bounds; held drag shrinks and reverses without locking; release docks; subsequent square drag stays small and survives refresh`);
  await p.emulateMedia({reducedMotion:'reduce'});await p.locator('.focus-square').click();assert.equal(await p.locator('.focus-clock').evaluate(n=>n.getAnimations().length),0);
  checks.push(`${width}px: reduced-motion expansion has no animation`);
  await p.evaluate(()=>{const k=Object.keys(localStorage).find(k=>k.startsWith('zhixu-focus-v1'));const s=JSON.parse(localStorage.getItem(k));s.active.startedAt=Date.now()-s.active.durationMs-1000;localStorage.setItem(k,JSON.stringify(s));});
  await p.locator('[data-action="focus-break"]').waitFor();
  const h=await p.locator('.focus-drag').boundingBox();
  await p.mouse.move(h.x+h.width/2,h.y+h.height/2);await p.mouse.down();await p.mouse.move(dock.x+18,dock.y+18,{steps:12});await p.mouse.up();
  await p.locator('.focus-mini').waitFor();await p.locator('.focus-square').click();await p.locator('[data-action="focus-break"]').waitFor();
  checks.push(`${width}px: completed timer can also be docked and reopened`);
  await context.close();
 }
 assert.deepEqual(errors,[]);
 fs.writeFileSync(path.join(out,'results.json'),JSON.stringify({checks,errors,at:new Date().toISOString(),syntheticRoot:meta.root},null,2));
 console.log(JSON.stringify({checks,errors}));
}finally{await browser.close();}
